import fs from 'node:fs'
import dotenv from 'dotenv'
import { websitePackages } from '../src/shared/website-packages'

const production = process.argv.includes('--production')
if (production) {
  const env = dotenv.parse(fs.readFileSync('.local/vercel.production.env'))
  const connection = env.DATABASE_URL_UNPOOLED || env.DATABASE_URL
  if (!new URL(connection).hostname.endsWith('.neon.tech')) throw new Error('Unexpected production database')
  Object.assign(process.env, env, { DATABASE_URL: connection })
} else dotenv.config()
const { pool } = await import('../src/backend/database')
const { validateDocument } = await import('../src/backend/content-validation')
const checked = validateDocument('site-settings', { websitePackages }, true)
if (!checked.data) throw new Error(checked.error)
const client = await pool.connect()
try {
  await client.query('BEGIN')
  const before = await client.query("SELECT slug,data,revision FROM studio_globals WHERE slug IN ('site-settings','navigation') FOR UPDATE")
  fs.writeFileSync(`.local/packages-${production ? 'production' : 'local'}-${Date.now()}.json`, JSON.stringify(before.rows), { mode: 0o600 })
  const settings = before.rows.find(row => row.slug === 'site-settings')
  const navigation = before.rows.find(row => row.slug === 'navigation')
  if (!settings || !navigation) throw new Error('Website has not been initialized')
  if (!settings.data.websitePackages) {
    await client.query("UPDATE studio_globals SET data=data||$1::jsonb,revision=revision+1,updated_at=now() WHERE slug='site-settings'", [JSON.stringify(checked.data)])
    console.log('Added the three owner-approved website packages.')
  } else console.log('Preserved existing CMS package data.')
  if (!(navigation.data.links || []).some((item: { href: string }) => item.href === '/paket-website')) {
    const links = [...(navigation.data.links || [])]
    links.splice(Math.min(2, links.length), 0, { id: 'paket-website', label: 'Paket', href: '/paket-website', enabled: true, order: 25 })
    await client.query("UPDATE studio_globals SET data=data||$1::jsonb,revision=revision+1,updated_at=now() WHERE slug='navigation'", [JSON.stringify({ links })])
    console.log('Added package navigation while preserving current links.')
  }
  await client.query('COMMIT')
} catch (error) { await client.query('ROLLBACK'); throw error }
finally { client.release(); await pool.end() }
