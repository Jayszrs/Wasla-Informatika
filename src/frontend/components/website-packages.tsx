import Link from 'next/link'
import { websitePackages, type WebsitePackage } from '@/shared/website-packages'
import { PackageDeck } from './package-deck'

export function WebsitePackages({ packages, standalone = false }: { packages?: WebsitePackage[] | null; standalone?: boolean }) {
  const plans = packages ?? websitePackages
  return <section className={`website-packages wrap ${standalone ? 'packages-standalone' : ''}`} aria-labelledby="packages-title">
    <div className="packages-heading"><h2 id="packages-title">{standalone ? 'Pilih layanan untuk rencana Anda.' : 'Paket layanan.'}</h2><p>Website, fotografi, dan video editing. Pilih kebutuhan Anda, lalu kita susun rincian pengerjaannya bersama.</p></div>
    <div className="package-decks">{[
      { title: 'Website & aplikasi', plans: plans.filter(plan => !/fotografi|video|editing/i.test(plan.service)) },
      { title: 'Foto & video', plans: plans.filter(plan => /fotografi|video|editing/i.test(plan.service)) },
    ].filter(group => group.plans.length).map(group => <PackageDeck key={group.title} title={group.title} plans={group.plans}/>)}{!plans.length && <p className="packages-empty">Paket sedang diperbarui. <Link href="/kontak">Diskusikan kebutuhan Anda.</Link></p>}</div>
    <p className="packages-note">Rincian hasil, jadwal, lokasi, revisi, dan biaya tambahan disepakati dalam penawaran. Untuk website, domain, hosting, serta dukungan mengikuti lingkup project.</p>{!standalone && <Link className="text-link" href="/paket-website">Lihat seluruh paket layanan</Link>}
  </section>
}
