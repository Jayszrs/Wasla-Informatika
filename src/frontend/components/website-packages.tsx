import Link from 'next/link'
import { websitePackages, formatRupiah, packageConsultationURL, type WebsitePackage } from '@/shared/website-packages'
import { localizedPath, translate } from '@/shared/i18n'
import { getLocale } from '@/frontend/lib/locale'
import styles from './website-packages.module.css'

export async function WebsitePackages({ packages, standalone = false }: { packages?: WebsitePackage[] | null; standalone?: boolean }) {
  const locale = await getLocale()
  const t = (text: string) => translate(text, locale)
  const plans = packages ?? websitePackages
  const groups = [
    { title: 'Website & aplikasi', plans: plans.filter(plan => !/fotografi|video|editing/i.test(plan.service)) },
    { title: 'Foto & video', plans: plans.filter(plan => /fotografi|video|editing/i.test(plan.service)) },
  ].filter(group => group.plans.length)
  return <section className={`website-packages wrap ${standalone ? 'packages-standalone' : ''}`} aria-labelledby="packages-title">
    <div className="packages-heading">
      <h2 id="packages-title">{t(standalone ? 'Pilih layanan untuk rencana Anda.' : 'Paket layanan.')}</h2>
      <p>{t('Website, fotografi, dan video editing. Pilih kebutuhan Anda, lalu kita susun rincian pengerjaannya bersama.')}</p>
    </div>
    <div className={styles.groups}>
      {groups.map(group => <section className={styles.group} key={group.title} aria-label={t(group.title)}>
        <h3 className={styles.groupTitle}>{t(group.title)}</h3>
        <div className={styles.grid}>{group.plans.map(plan => <article className={`${styles.card} package-card`} key={plan.slug} data-package-slug={plan.slug}>
          <h4 className={styles.name}>{t(plan.name)}</h4>
          <div className={styles.price}>
            <span className={styles.prefix} aria-hidden={!plan.startingPrice}>{plan.startingPrice ? t('Mulai dari') : ''}</span>
            <strong>{formatRupiah(plan.price)}</strong>
            <span className={styles.priceUnit}>{plan.priceUnit ? t(plan.priceUnit) : t(plan.cms)}</span>
          </div>
          <p className={styles.description}>{t(plan.description)}</p>
          {plan.priceUnit && <p className={styles.scope}>{t(plan.cms)}</p>}
          <Link className={styles.action} href={localizedPath(packageConsultationURL(plan), locale)} aria-label={`${t('Konsultasi paket')} ${t(plan.name)}`}>{t('Bahas paket ini')}</Link>
        </article>)}</div>
      </section>)}
      {!plans.length && <p className="packages-empty">{t('Paket sedang diperbarui.')} <Link href={localizedPath('/kontak', locale)}>{t('Diskusikan kebutuhan Anda.')}</Link></p>}
    </div>
    <p className="packages-note">{t('Rincian hasil, jadwal, lokasi, revisi, dan biaya tambahan disepakati dalam penawaran. Untuk website, domain, hosting, serta dukungan mengikuti lingkup project.')}</p>
    {!standalone && <Link className="text-link" href={localizedPath('/paket-website', locale)}>{t('Lihat seluruh paket layanan')}</Link>}
  </section>
}
