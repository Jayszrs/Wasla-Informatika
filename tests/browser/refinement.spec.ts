import { test, expect } from '@playwright/test'

test('actual WebGL service geometry responds to keyboard, pointer and scroll', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/layanan')
  const viewport = page.locator('.service-scene-viewport').first()
  await viewport.scrollIntoViewIfNeeded()
  const canvas = viewport.locator('canvas[data-rendered3d=true]')
  await expect(canvas).toBeVisible({ timeout: 30000 })
  await expect(viewport).toHaveAttribute('data-ready', 'true')
  const before = await canvas.screenshot()
  await canvas.focus(); await page.keyboard.press('ArrowRight'); await page.keyboard.press('ArrowRight')
  await expect.poll(async () => Buffer.compare(before, await canvas.screenshot())).not.toBe(0)
  const bounds = await canvas.boundingBox(); if (!bounds) throw Error('3D canvas unavailable')
  await page.mouse.move(bounds.x + bounds.width * .5, bounds.y + bounds.height * .5)
  await page.mouse.down(); await page.mouse.move(bounds.x + bounds.width * .75, bounds.y + bounds.height * .6, { steps: 8 }); await page.mouse.up()
  const drag = await canvas.screenshot(); expect(Buffer.compare(before, drag)).not.toBe(0)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await canvas.focus(); await page.keyboard.press('Home')
  await expect(canvas).toBeVisible()
})

test('flip cards, plain public links, white CTA, technologies and project gallery', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('.header-emblem')).toHaveCount(0)
  await expect(page.locator('.technology-logos a')).toHaveCount(24)
  const technology = page.locator('.technology-logos a').first()
  await technology.focus()
  await expect.poll(() => technology.locator('img').evaluate(el => getComputedStyle(el).filter)).toBe('none')
  const card = page.locator('.division-flip-card').first()
  const trigger = card.getByRole('button', { name: /^Kenali / })
  await trigger.focus(); await page.keyboard.press('Enter')
  await expect(card).toHaveClass(/is-flipped/)
  await expect(card.getByRole('link', { name: 'Hubungi via WhatsApp' })).toHaveAttribute('href', /^https:\/\/wa\.me\/62/)
  await card.getByRole('button', { name: /^Kembali ke kartu/ }).click()
  await expect(card).not.toHaveClass(/is-flipped/)
  expect(await page.locator('.consultation-section').evaluate(el => getComputedStyle(el).backgroundColor)).toBe('rgb(255, 255, 255)')
  await page.goto('/portofolio')
  expect(await page.locator('.project-live').first().evaluate(el => getComputedStyle(el).textDecorationLine)).toBe('none')
  await expect(page.locator('.project-live svg')).toHaveCount(0)
  await page.goto('/portofolio/catatan-mengaji-bani-saleh')
  await expect(page.locator('.gallery-grid figure')).toHaveCount(3)
  const gallery = page.getByRole('link', { name: /^Perbesar gambar 1:/ })
  await gallery.focus(); await page.keyboard.press('Enter')
  const dialog = page.getByRole('dialog', { name: 'Galeri project diperbesar' })
  await expect(dialog).toBeVisible(); await page.keyboard.press('ArrowRight')
  await expect(dialog.locator('.gallery-controls p')).toContainText('2 / 3')
  await page.keyboard.press('Escape'); await expect(gallery).toBeFocused()
  await page.goto('/layanan')
  expect(await page.locator('.final-cta').evaluate(el => getComputedStyle(el).backgroundColor)).toBe('rgb(255, 255, 255)')
  await expect(page.locator('.site-footer>.section-wave')).toHaveCount(0)
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
