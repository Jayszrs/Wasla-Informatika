import { test, expect, type Locator, type Page } from '@playwright/test'

async function dragDevice(page: Page, stage: Locator) {
  const bounds = await stage.boundingBox()
  if (!bounds) throw Error('Device preview unavailable')
  await page.mouse.move(bounds.x + bounds.width * .45, bounds.y + bounds.height * .45)
  await page.mouse.down()
  await page.mouse.move(bounds.x + bounds.width * .7, bounds.y + bounds.height * .58, { steps: 12 })
  await page.mouse.up()
}

test('dragging a project rotates its real mesh without navigating; a normal click still follows its link', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/')
  const stage = page.locator('.homepage-projects .device3d-stage').first()
  await stage.scrollIntoViewIfNeeded()
  const canvas = stage.locator('canvas[data-rendered3d=true]')
  await expect(canvas).toBeVisible({ timeout: 30000 })
  const previous = await canvas.getAttribute('data-rotation')
  const location = page.url()
  const link = stage.locator('xpath=..')
  const href = await link.getAttribute('href')
  await dragDevice(page, stage)
  await expect.poll(() => canvas.getAttribute('data-rotation')).not.toBe(previous)
  expect(page.url()).toBe(location)
  await expect(stage).not.toHaveAttribute('data-device-dragging', 'true')
  await link.click()
  await expect(page).toHaveURL(new RegExp(`${href}$`))
})

test('tablet preview supports bounded drag and keyboard rotation while ordinary clicks enlarge the image', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/portofolio/sit-permata-hati-bekasi')
  const stage = page.locator('.gallery-device-stage[data-device-kind=tablet]')
  await stage.scrollIntoViewIfNeeded()
  const canvas = stage.locator('canvas[data-rendered3d=true]')
  await expect(canvas).toBeVisible({ timeout: 30000 })
  await dragDevice(page, stage)
  await expect(page.getByRole('dialog')).not.toBeVisible()
  const link = stage.locator('xpath=..')
  await link.focus()
  const before = await canvas.getAttribute('data-rotation')
  await page.keyboard.press('ArrowLeft')
  await expect.poll(() => canvas.getAttribute('data-rotation')).not.toBe(before)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.keyboard.press('Home')
  await expect.poll(() => canvas.getAttribute('data-rotation')).toBe('-0.110,-0.180')
  await page.keyboard.press('ArrowRight')
  await expect.poll(() => canvas.getAttribute('data-rotation')).toBe('-0.110,-0.080')
  await page.keyboard.press('Escape')
  await expect.poll(() => canvas.getAttribute('data-rotation')).toBe('-0.110,-0.180')
  await link.click()
  await expect(page.getByRole('dialog')).toBeVisible()
})

test('touch scrolling over a device remains native and a tap still opens the gallery', async ({ browser, baseURL }) => {
  const context = await browser.newContext({ baseURL, viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
  const page = await context.newPage()
  try {
    await page.goto('/portofolio/sit-permata-hati-bekasi')
    const stage = page.locator('.gallery-device-stage[data-device-kind=tablet]')
    await stage.scrollIntoViewIfNeeded()
    await expect(stage.locator('canvas[data-rendered3d=true]')).toBeVisible({ timeout: 30000 })
    const before = await page.evaluate(() => scrollY)
    const bounds = await stage.boundingBox()
    if (!bounds) throw Error('Tablet preview unavailable')
    const session = await context.newCDPSession(page)
    await session.send('Input.synthesizeScrollGesture', { x: Math.round(bounds.x + bounds.width / 2), y: Math.round(bounds.y + bounds.height / 2), yDistance: -230, speed: 700, gestureSourceType: 'touch' })
    await expect.poll(() => page.evaluate(() => scrollY)).toBeGreaterThan(before)
    await expect(page.getByRole('dialog')).not.toBeVisible()
    await stage.scrollIntoViewIfNeeded()
    const finalBounds = await stage.boundingBox()
    if (!finalBounds) throw Error('Tablet preview unavailable after scrolling')
    await page.touchscreen.tap(finalBounds.x + finalBounds.width / 2, finalBounds.y + finalBounds.height / 2)
    await expect(page.getByRole('dialog')).toBeVisible()
  } finally { await context.close() }
})
